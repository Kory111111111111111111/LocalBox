// Generate src/lib/tools.generated.ts + public/sitemap.xml + public/llms.txt
// + public/robots.txt from the research pack's tools.json (single source of truth).
//
// Usage: node scripts/gen-registry.mjs
// Override site origin for production sitemaps: LTB_SITE_URL=https://yourdomain
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SOURCE = process.env.LTB_TOOLS_JSON || path.join(root, "..", "tools.json");
const SITE = process.env.LTB_SITE_URL || "http://localhost:5173";

const pack = JSON.parse(readFileSync(SOURCE, "utf8"));

// Slugs that must touch the network (documented exceptions; every one shows a banner).
const NETWORK_TOOLS = new Set([
  "dns-lookup", "whois", "ping-tool", "ssl-checker", "network-speed-test",
  "ip-address", "port-checker", "og-preview", "youtube-thumbnail",
]);

// Slugs that download an AI model once, cache it, then run offline.
const MODEL_TOOLS = {
  "background-remover": "~28 MB MODNet model (Apache-2.0) — downloads once, then works offline.",
  "transcribe": "~75 MB Whisper tiny model — downloads once, then works offline.",
  "subtitle-generator": "~75 MB Whisper tiny model — downloads once, then works offline.",
};

// ffmpeg.wasm-backed video/audio tools (WASM, but still fully local).
const WASM_EXEMPT = new Set(["screen-recorder", "text-to-speech", "transcribe", "subtitle-generator"]);

const ICON_ALIASES = { CropIcon: "Crop", TimerIcon: "Timer", Globe2: "Globe", Twitter: "Share2", Youtube: "Youtube" };

function esc(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const categories = pack.categories.map((c) => ({
  id: c.id,
  name: c.name,
  description: c.description,
  icon: c.icon,
}));

const tools = pack.tools.map((t) => ({
  id: t.id,
  slug: t.id,
  name: t.name,
  description: t.description.replace(/\s+—\s+.*$/, ""), // strip reference-site taglines
  category: t.category,
  tags: (t.tags || []).slice(0, 8),
  icon: ICON_ALIASES[t.icon] || t.icon || null,
  featured: !!t.isFeatured,
  needsNetwork: NETWORK_TOOLS.has(t.id),
  needsModel: t.id in MODEL_TOOLS,
  modelNote: MODEL_TOOLS[t.id] || null,
  needsWasm: t.category === "video" && !WASM_EXEMPT.has(t.id),
}));

// sanity: 316 tools, 16 categories, slugs unique
const slugs = new Set(tools.map((t) => t.slug));
if (tools.length !== 316) throw new Error(`expected 316 tools, got ${tools.length}`);
if (slugs.size !== tools.length) throw new Error("duplicate slugs");
if (categories.length !== 16) throw new Error(`expected 16 categories, got ${categories.length}`);

const ts = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.
// Source of truth: tools.json (research pack). Regenerate with: pnpm gen

export type RawTool = {
  id: string; slug: string; name: string; description: string;
  category: string; tags: string[]; icon: string | null;
  featured: boolean; needsNetwork: boolean; needsModel: boolean;
  modelNote: string | null; needsWasm: boolean;
};

export type RawCategory = { id: string; name: string; description: string; icon: string };

export const RAW_CATEGORIES: RawCategory[] = ${JSON.stringify(categories, null, 2)};

export const RAW_TOOLS: RawTool[] = ${JSON.stringify(tools, null, 2)};
`;

mkdirSync(path.join(root, "src/lib"), { recursive: true });
writeFileSync(path.join(root, "src/lib/tools.generated.ts"), ts, "utf8");

// ---------- sitemap.xml ----------
const pages = ["", "/about", "/privacy", "/terms", "/contact"];
const urls = [
  ...pages.map((p) => SITE + "/" + p),
  ...categories.map((c) => `${SITE}/category/${c.id}`),
  ...tools.map((t) => `${SITE}/tools/${t.slug}`),
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
  .map((u) => `  <url><loc>${u}</loc></url>`)
  .join("\n")}\n</urlset>\n`;
writeFileSync(path.join(root, "public/sitemap.xml"), sitemap, "utf8");

// ---------- llms.txt ----------
let llms = `# LocalToolBox

> LocalToolBox is an open-source, privacy-first toolbox of ${tools.length} browser utilities across ${categories.length} categories. All processing runs client-side in the browser. No accounts, no uploads, no watermarks, no ads. A few network tools (DNS, WHOIS, IP info...) are clearly labeled. AI tools download a local model once, cache it, and then work offline.

## Info pages

- [About](${SITE}/about): mission and privacy stance
- [Privacy](${SITE}/privacy): what stays on your device (everything except labeled network lookups)
- [Terms](${SITE}/terms): terms of use
- [Contact](${SITE}/contact): feedback and questions

## Categories

${categories.map((c) => `- [${c.name}](${SITE}/category/${c.id}): ${c.description} (${tools.filter((t) => t.category === c.id).length} tools)`).join("\n")}

## Tools

${tools
  .map((t) => {
    const flag = t.needsNetwork ? " [needs network]" : t.needsModel ? " [downloads model once]" : "";
    return `- [${t.name}](${SITE}/tools/${t.slug}): ${t.description}${flag}`;
  })
  .join("\n")}
`;
writeFileSync(path.join(root, "public/llms.txt"), llms, "utf8");

// ---------- robots.txt ----------
writeFileSync(
  path.join(root, "public/robots.txt"),
  `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`,
  "utf8",
);

console.log(`gen-registry: ${tools.length} tools, ${categories.length} categories -> tools.generated.ts`);
console.log(`gen-registry: sitemap.xml (${urls.length} urls), llms.txt, robots.txt written with origin ${SITE}`);
